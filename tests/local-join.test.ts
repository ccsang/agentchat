import { afterEach, beforeEach, expect, test } from "bun:test";
import { existsSync, lstatSync, mkdirSync, readFileSync, symlinkSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { randomUUID } from "node:crypto";
import { applyInstall, planInstall, preview } from "../src/install.ts";
import { integrationSettings, workspaceDir } from "../src/workspace.ts";
import { writeJson } from "../src/files.ts";
import { registerHook } from "../src/hooks.ts";
import { cli, fixture, git, testEnv } from "./helpers.ts";

let f: ReturnType<typeof fixture>;
beforeEach(() => { f = fixture(); }); afterEach(() => f.cleanup());
test("join and room use leave tracked instructions, malformed hooks and git status unchanged", () => {
  git(f.root, ["init", "-b", "main"]);
  writeFileSync(join(f.root, "AGENTS.md"), "Existing agent rules\n"); writeFileSync(join(f.root, "CLAUDE.md"), "Existing Claude rules\n");
  mkdirSync(join(f.root, ".claude")); writeFileSync(join(f.root, ".claude/settings.local.json"), "{malformed existing configuration\n");
  git(f.root, ["add", "-f", "AGENTS.md", "CLAUDE.md", ".claude/settings.local.json"]);
  git(f.root, ["-c", "user.name=Test", "-c", "user.email=test@example.invalid", "commit", "-m", "user files"]);
  const exclude = readFileSync(join(f.root, ".git/info/exclude"), "utf8");
  const env = testEnv({ CODEX_THREAD_ID: randomUUID() });
  const first = cli(f.root, ["join"], env);
  expect(first.status).toBe(0); expect(first.data.initialization.runtime_only).toBe(true); expect(first.data.initialization.project_file_changes).toEqual([]);
  expect(cli(f.root, ["room", "create", "review"], env).status).toBe(0);
  expect(cli(f.root, ["room", "use", "review"], env).status).toBe(0);
  expect(cli(f.root, ["join"], env).data.initialization.initialized).toBe(false);
  expect(git(f.root, ["status", "--porcelain", "--untracked-files=all"])).toBe("");
  expect(readFileSync(join(f.root, ".git/info/exclude"), "utf8")).toBe(exclude);
});
test("default local setup does not follow instruction symlinks or parse unrelated project configuration", async () => {
  const target = join(f.root, "user-rules"); writeFileSync(target, "Keep unchanged\n");
  symlinkSync(target, join(f.root, "AGENTS.md")); writeFileSync(join(f.root, "CLAUDE.md"), "<!-- agentchat:begin -->\nmalformed old block\n");
  mkdirSync(join(f.root, ".claude")); writeFileSync(join(f.root, ".claude/settings.local.json"), "invalid JSON");
  const plan = await planInstall(f.project);
  expect(preview(plan).runtime_only).toBe(true); expect(plan.hooks).toEqual({});
  applyInstall(plan);
  expect(lstatSync(join(f.root, "AGENTS.md")).isSymbolicLink()).toBe(true); expect(readFileSync(target, "utf8")).toBe("Keep unchanged\n");
  expect(readFileSync(join(f.root, ".claude/settings.local.json"), "utf8")).toBe("invalid JSON");
});
test("instruction integration is explicit, independent of hooks, and can be removed without disabling local messaging", async () => {
  mkdirSync(join(f.root, ".claude")); const path = join(f.root, ".claude/settings.local.json"); writeFileSync(path, "unrelated invalid JSON");
  writeFileSync(join(f.root, "AGENTS.md"), "Business rules\n");
  const plan = await planInstall(f.project, { instructions: true });
  expect(preview(plan).project_file_changes).toEqual([join(f.root, "AGENTS.md"), join(f.root, "CLAUDE.md")]);
  applyInstall(plan);
  expect(readFileSync(path, "utf8")).toBe("unrelated invalid JSON"); expect(integrationSettings(f.project)).toEqual({ instructions: true, hooks: false });
  applyInstall(await planInstall(f.project, { uninstall: true, instructions: true }));
  expect(readFileSync(join(f.root, "AGENTS.md"), "utf8")).toBe("Business rules\n");
  expect(integrationSettings(f.project)).toEqual({ instructions: false, hooks: false });
  expect(cli(f.root, ["join", "--generic", "--name", "operator"]).status).toBe(0);
});
test("a stale local-only plan cannot erase a newly enabled optional integration", async () => {
  applyInstall(await planInstall(f.project));
  const stale = await planInstall(f.project);
  applyInstall(await planInstall(f.project, { hooks: true }));
  expect(() => applyInstall(stale)).toThrow("integration selection changed since preview");
  expect(integrationSettings(f.project)).toEqual({ instructions: false, hooks: true });
  expect(JSON.parse(readFileSync(join(f.root, ".claude/settings.local.json"), "utf8")).hooks.SessionStart).toHaveLength(1);
});
test("hook integration does not read or rewrite instructions and preserves user hooks on removal", async () => {
  const rules = "<!-- agentchat:begin -->\nuser-owned incomplete block\n";
  writeFileSync(join(f.root, "AGENTS.md"), rules);
  mkdirSync(join(f.root, ".claude")); const path = join(f.root, ".claude/settings.local.json");
  const user = { type: "command", command: "user-hook" };
  writeFileSync(path, JSON.stringify({ permissions: { deny: ["user-rule"] }, hooks: { Stop: [{ hooks: [user] }] } }));
  applyInstall(await planInstall(f.project, { hooks: true }));
  expect(readFileSync(join(f.root, "AGENTS.md"), "utf8")).toBe(rules); expect(existsSync(join(f.root, "CLAUDE.md"))).toBe(false);
  expect(integrationSettings(f.project)).toEqual({ instructions: false, hooks: true });
  applyInstall(await planInstall(f.project, { uninstall: true, hooks: true }));
  const after = JSON.parse(readFileSync(path, "utf8"));
  expect(after.hooks).toEqual({ Stop: [{ hooks: [user] }] }); expect(after.permissions.deny).toEqual(["user-rule"]);
  expect(integrationSettings(f.project)).toEqual({ instructions: false, hooks: false });
  expect(registerHook(f.project, { session_id: randomUUID(), cwd: f.root, hook_event_name: "SessionStart" }, {})).toEqual({});
  expect(existsSync(join(f.project.room, "chat.db"))).toBe(false);
});
test("legacy setup is upgraded locally without repairing or deleting its existing project files", async () => {
  applyInstall(await planInstall(f.project, { instructions: true, hooks: true }));
  const workspace = join(workspaceDir(f.project), "installed.json"), shared = join(f.project.room, "installed.json");
  const previous = JSON.parse(readFileSync(workspace, "utf8")); delete previous.setupVersion; delete previous.integration;
  writeJson(workspace, previous); writeJson(shared, previous);
  writeFileSync(join(f.root, "AGENTS.md"), "Changed by the user\n<!-- agentchat:begin -->\n");
  writeFileSync(join(f.root, ".claude/settings.local.json"), "User changed this to invalid JSON");
  const first = cli(f.root, ["join"], testEnv({ CODEX_THREAD_ID: randomUUID() }));
  expect(first.status).toBe(0); expect(first.data.initialization.runtime_only).toBe(true);
  expect(readFileSync(join(f.root, "AGENTS.md"), "utf8")).toBe("Changed by the user\n<!-- agentchat:begin -->\n");
  expect(readFileSync(join(f.root, ".claude/settings.local.json"), "utf8")).toBe("User changed this to invalid JSON");
  expect(integrationSettings(f.project)).toEqual({ instructions: true, hooks: true });
});
test("joining does not implicitly enable Channel hooks, even when instructions were explicitly installed", () => {
  const env = testEnv({ AGENTCHAT_CLAUDE_SESSION_ID: randomUUID() });
  expect(cli(f.root, ["join"], env).status).toBe(0);
  expect(cli(f.root, ["channel-config", "--apply"], env).data.error.code).toBe("E_CONFIG");
  expect(existsSync(join(f.root, ".claude"))).toBe(false);
  expect(cli(f.root, ["install", "--instructions", "--apply"], env).status).toBe(0);
  expect(cli(f.root, ["channel-config", "--apply"], env).data.error.code).toBe("E_CONFIG");
  expect(cli(f.root, ["install", "--hooks", "--apply"], env).status).toBe(0);
  expect(cli(f.root, ["channel-config", "--apply"], env).status).toBe(0);
});
test("a new worktree does not inherit optional integration from the shared metadata fallback", () => {
  git(f.root, ["init", "-b", "main"]);
  git(f.root, ["-c", "user.name=Test", "-c", "user.email=test@example.invalid", "commit", "--allow-empty", "-m", "fixture"]);
  expect(cli(f.root, ["install", "--instructions", "--hooks", "--apply"]).status).toBe(0);
  const linked = join(f.root, "linked"); git(f.root, ["worktree", "add", "-b", "linked", linked]);
  const env = testEnv({ AGENTCHAT_CLAUDE_SESSION_ID: randomUUID() });
  const first = cli(linked, ["join"], env);
  expect(first.status).toBe(0);
  expect(first.data.initialization.integration).toEqual({ instructions: false, hooks: false });
  expect(existsSync(join(linked, "AGENTS.md"))).toBe(false); expect(existsSync(join(linked, ".claude"))).toBe(false);
  expect(cli(linked, ["channel-config", "--apply"], env).data.error.code).toBe("E_CONFIG");
  expect(cli(f.root, ["join"], env).data.initialization.initialized).toBe(false);
  expect(cli(f.root, ["channel-config", "--apply"], env).status).toBe(0);
});
